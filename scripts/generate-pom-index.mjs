/**
 * Write docs/kb/pom-index.md from the page and component classes.
 *   npm run index:pom
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  path.join(root, 'src', 'pages'),
  path.join(root, 'src', 'components'),
];
const output = path.join(root, 'docs', 'kb', 'pom-index.md');

function methodsAndProperties(source) {
  const properties = [];
  const methods = [];
  const propertyPattern = /^\s+(?:public\s+|private\s+|readonly\s+)+(\w+)\s*:/gm;
  const methodPattern = /^\s+(?:public\s+|private\s+|async\s+)+(\w+)\s*\(([^)]*)\)\s*:\s*Promise</gm;
  let match = propertyPattern.exec(source);
  while (match) {
    if (!['page'].includes(match[1])) properties.push(match[1]);
    match = propertyPattern.exec(source);
  }
  match = methodPattern.exec(source);
  while (match) {
    const params = match[2].replace(/\s+/g, ' ').trim();
    methods.push(`${match[1]}(${params})`);
    match = methodPattern.exec(source);
  }
  return { properties, methods };
}

const lines = [
  '# Page object index',
  '',
  'Generated by `npm run index:pom`. Reuse these methods before adding a new one.',
  '',
];

for (const directory of sources) {
  const files = fs.readdirSync(directory).filter((name) => name.endsWith('.ts')).sort();
  for (const file of files) {
    const relative = path.posix.join(path.relative(root, directory).replaceAll('\\', '/'), file);
    const source = fs.readFileSync(path.join(directory, file), 'utf8');
    const className = source.match(/export class (\w+)/)?.[1] ?? file.replace(/\.ts$/, '');
    const { properties, methods } = methodsAndProperties(source);
    lines.push(`## ${className}`);
    lines.push('');
    lines.push(`File: \`${relative}\``);
    lines.push('');
    lines.push(`Locators: ${properties.length ? properties.map((name) => `\`${name}\``).join(', ') : 'none'}`);
    lines.push('');
    lines.push('Methods:');
    lines.push('');
    if (methods.length === 0) lines.push('- none');
    for (const method of methods) lines.push(`- \`${method}\``);
    lines.push('');
  }
}

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, `${lines.join('\n')}\n`);
console.log(`Wrote ${path.relative(root, output)}`);
